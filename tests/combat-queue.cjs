/* SLASHER 1.1 · testes da fila de combate em Node 22. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const crypto=require('node:crypto').webcrypto;
const T=require('../combat-queue.js');
const char=(id,name,hp=12)=>({id,name,hp,hp_max:12,stamina:10,stress:0,owner_id:'player'});
const monster=(id,name,hp=18)=>({id,name,hp,hp_max:18,defense:12,damage_sides:6});
const chars=[char('c1','Elisa'),char('c2','Daniel')],mons=[monster('m1','Cultista')];
let e=T.start({campaign_id:'camp'},chars,mons,1);
assert.equal(e.active,true);
assert.equal(e.round,1);
assert.equal(e.queue.length,3);
assert.equal(e.currentKey,'c:c1');
assert.equal(e.turn_label,'Elisa');
assert.equal(T.status(e,chars,mons).entries[0].state,'current');
e=T.advance(e,chars,mons);
assert.equal(e.currentKey,'c:c2');
assert.equal(T.status(e,chars,mons).entries[0].state,'acted');
e=T.advance(e,chars,mons);
assert.equal(e.currentKey,'m:m1');
e=T.advance(e,chars,mons);
assert.equal(e.currentKey,null);
assert.equal(T.status(e,chars,mons).complete,true);
const stale=T.reconcile(e,chars,mons);
assert.equal(stale.currentKey,null,'concluir rodada não inicia nova automaticamente');
e=T.newRound(e,chars,mons);
assert.equal(e.round,2);
assert.equal(e.currentKey,'c:c1');
assert(e.queue.every(x=>!x.acted));
const defeated=[char('c1','Elisa',0),chars[1]];
const afterDeath=T.reconcile(e,defeated,mons);
assert.equal(afterDeath.currentKey,'c:c2');
assert.equal(T.status(afterDeath,defeated,mons).entries[0].state,'fallen');
const withReinforcements=T.reconcile(afterDeath,defeated,[...mons,monster('m2','Outro Cultista')]);
assert.equal(withReinforcements.queue.length,4);
assert.equal(withReinforcements.queue.at(-1).key,'m:m2');
assert.equal(T.reconcile(withReinforcements,defeated,[...mons,monster('m2','Outro Cultista')]).queue.length,4,'sem duplicação');
assert.equal(T.reconcile(withReinforcements,defeated,mons).queue.length,3,'remoção de combatente inexistente');
const inactive=T.reconcile({active:false,queue:withReinforcements.queue},chars,mons);
assert.equal(inactive.queue.length,0);
assert.throws(()=>T.advance({active:false},chars,mons),/Inicie/);
// Integração real com o módulo Mesa Atual da versão 1.0.
const values=new Map();
const storage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)};
const win={SLASHER_TURNS:T,SLASHER_DICE:{face:()=>10}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../mesa71.js'),'utf8'),{window:win,localStorage:storage,crypto,console,Date,Math,JSON,Number,performance:{now:()=>0}});
const state={campaignId:'camp',campaign:{id:'camp',name:'SLASHER'},mode:'local',members:[{user_id:'gm',role:'gm'},{user_id:'player',role:'player'}],user:{id:'gm'},characters:chars,selected:'c1',effects:[],gmPreview:false};
(async()=>{
 await win.SLASHER71.load(state,{});
 const remote=(op,args={},who='gm')=>win.SLASHER71.remote(state,op,args,who);
 remote('monster_create',{p_name:'Cultista',p_hp:18,p_defense:12,p_damage:6});
 remote('encounter_set',{p_active:true,p_round:1});
 assert.equal(state.mesa71.encounter.queue.length,3);
 assert(win.SLASHER71.render(state).includes('Fila de ação'));
 assert(win.SLASHER71.render(state).includes('Concluir turno'));
 remote('turn_advance');
 assert.equal(state.mesa71.encounter.currentKey,'c:c2');
 assert.throws(()=>remote('turn_advance',{},'player'),/Apenas o mestre/);
 remote('turn_new_round');
 assert.equal(state.mesa71.encounter.round,2);
 remote('monster_create',{p_name:'Nova ameaça',p_hp:12,p_defense:11,p_damage:4});
 assert.equal(state.mesa71.encounter.queue.length,4);
 assert(values.has('slasher71_local_camp'));
 remote('encounter_set',{p_active:false,p_round:2});
 assert.equal(state.mesa71.encounter.active,false);
 assert(!win.SLASHER71.render(state).includes('Fila de ação'));
 const page=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
 assert(page.includes('combat-queue.js?v=1.1.0'));
 assert(page.includes('combat-queue.css?v=1.1.0'));
 console.log('PASS: ordem, rodada, quedas, novos participantes, permissão GM, persistência, interface e scripts');
})().catch(e=>{console.error(e);process.exitCode=1});
